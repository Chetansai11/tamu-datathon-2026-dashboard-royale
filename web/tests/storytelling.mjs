/** Integration checks for the new evidence presentation, against official compact data. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {JSDOM,VirtualConsole} from 'jsdom';
const web=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const data=JSON.parse(fs.readFileSync(path.join(web,'public/data/dashboard.json'),'utf8'));
const compiled=await build({entryPoints:[path.join(web,'src/main.tsx')],bundle:true,write:false,format:'iife',platform:'browser',loader:{'.css':'empty'},define:{'process.env.NODE_ENV':'"production"'},logLevel:'silent'});
const errors=[];const vc=new VirtualConsole();vc.on('jsdomError',e=>errors.push(e.message));
const dom=new JSDOM('<!doctype html><html><body><script id="dashboard-payload" type="application/json"></script><div id="root"></div></body></html>',{url:'http://localhost/',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole:vc});
const w=dom.window;
w.document.getElementById('dashboard-payload').textContent=JSON.stringify(data);
w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
w.HTMLMediaElement.prototype.pause=()=>{};w.HTMLMediaElement.prototype.play=()=>Promise.resolve();
w.matchMedia=()=>({matches:false,addEventListener(){},removeEventListener(){}});
w.ResizeObserver=class{constructor(cb){this.cb=cb;}observe(el){this.cb([{target:el,contentRect:{width:1000,height:400}}]);}disconnect(){}};
w.addEventListener('error',e=>errors.push(e.error?.stack||e.message));
w.eval(compiled.outputFiles[0].text);
const settle=()=>new Promise(r=>setTimeout(r,90));
async function until(predicate,message){const deadline=Date.now()+5000;while(!predicate()&&Date.now()<deadline)await settle();assert.ok(predicate(),message);}
const label=s=>w.document.querySelector(`[aria-label="${s}"]`);
const named=(s,scope=w.document)=>[...scope.querySelectorAll('button')].find(b=>b.textContent.trim()===s);
async function click(el,message){assert.ok(el,message);el.focus();el.click();await settle();}
await until(()=>w.document.querySelector('.ace-overview'),'Overview loaded');
await click(label('Skip cinematic introduction'),'Skip automatic opening to inspect the analytical stories');
const heroBefore=w.document.querySelector('.ace-overview h1').textContent;
const waterfall=()=>w.document.querySelector('.gap-waterfall');
assert.ok(waterfall().textContent.includes('$0.02'),'Source rounding is disclosed');
assert.ok(waterfall().textContent.includes('3,764.90'),'Positive machine offset keeps exact dollars');
await click(label('Next earnings-gap step'),'Waterfall manual next works');
assert.equal(waterfall().dataset.step,'1','Manual selection advances the waterfall');
assert.equal(waterfall().dataset.playing,'false','Manual inspection pauses waterfall playback');
await click(named('Explore the floor'),'Explore opens the ten-machine evidence story');
const transition=()=>w.document.querySelector('.ace-floor-transition');
assert.ok(transition(),'Transition dialog mounts');
assert.equal(w.document.querySelector('.workspace').hasAttribute('inert'),true,'Underlying dashboard is inert');
assert.equal(transition().dataset.step,'0','Story starts with the shortlist');
const columns=Object.fromEntries(data.dailyColumns.map((key,index)=>[key,index]));
const candidateIds=data.reports.q1.bottom10.map(row=>row.machine_id);
const historicalBackForty=[...new Set(data.daily.filter(row=>row[columns.zone]==='Z-B40' && candidateIds.includes(data.machines[row[columns.machine]].id)).map(row=>data.machines[row[columns.machine]].id))].sort();
const cards=()=>[...transition().querySelectorAll('[data-machine-id]')];
assert.deepEqual(cards().map(m=>m.dataset.machineId),candidateIds,'All ten historical candidates appear in earnings order, including retired machines');
assert.deepEqual(cards().filter(m=>m.dataset.activeAtEnd==='false').map(m=>m.dataset.machineId).sort(),['M-1118','M-1120'],'Historical candidates absent by June 30 stay visible and explicitly marked');
assert.deepEqual(cards().filter(m=>m.dataset.shortExposure==='true').map(m=>m.dataset.machineId).sort(),['M-1118','M-1120','M-5076'],'Three shorter histories are disclosed');
for(const row of data.reports.q1.bottom10){
  const card=cards().find(m=>m.dataset.machineId===row.machine_id);
  assert.ok(card.textContent.includes(Math.round(row.house_win).toLocaleString('en-US')),`${row.machine_id} actual win agrees with published report`);
  assert.ok(card.textContent.includes(String(row.machine_days)),`${row.machine_id} active days give exposure context`);
}
transition().querySelector('.af-dialog').scrollTop=260;
await click(label('Next floor story step'),'Advance from shortlist to location');
assert.equal(transition().dataset.step,'1','Location is a separate manual chapter');
assert.equal(transition().querySelector('.af-dialog').scrollTop,0,'A new chapter returns its explanation to view after scrolling');
assert.deepEqual(cards().map(m=>m.dataset.machineId),candidateIds,'Location highlights preserve every card and its order');
assert.deepEqual(cards().filter(m=>m.dataset.backFortyHistory==='true').map(m=>m.dataset.machineId).sort(),historicalBackForty,'Historical location membership reconciles with actual daily placements');
assert.equal(historicalBackForty.length,9,'Nine candidates have Back Forty history');
await click(label('Next floor story step'),'Advance to inspection decision');
assert.equal(transition().dataset.step,'2','Decision is the third manual chapter');
const signal=cards().filter(m=>m.dataset.inspectionSignal==='true');
assert.deepEqual(signal.map(m=>m.dataset.machineId),['M-1158'],'Only the corrected payout signal is emphasized for inspection');
assert.equal(signal[0].dataset.backFortyHistory,'true','Inspection and location memberships overlap');
assert.deepEqual(cards().map(m=>m.dataset.machineId),candidateIds,'Inspection preserves context and card order');
assert.ok(/not proof|does not prove|not establish/i.test(transition().textContent),'Inspection is not presented as a proven fault');
await click(label('Previous floor story step'),'Manual backward navigation remains available');
assert.equal(transition().dataset.step,'1','Previous returns to the location chapter');
await click(named('Open six-month explorer',transition()),'Continue opens actual analysis');
assert.equal(transition(),null,'Transition closes after continuing');
assert.equal(w.location.hash,'#floor','Continue navigates to explorer');
assert.equal(label('Analysis period preset').value,'full','Explorer uses stated six-month scope');
assert.ok(w.document.querySelector('.workspace .panel').classList.contains('table-panel'),'Explorer leads with the machine list instead of dense full-floor charts');
assert.deepEqual([...w.document.querySelectorAll('.table-panel tbody tr')].map(row=>row.getAttribute('aria-label').replace('Inspect ','')),candidateIds,'Continuing carries the same ten candidates into the detailed explorer');
await click(named('The verdict'),'Return to overview');
await click(label('Toggle animations'),'Disable global motion');
assert.equal(waterfall().querySelectorAll('.gap-waterfall-column.is-revealed').length,6,'Motion off exposes all signed waterfall contributions');
assert.equal(label('Earnings-gap animation disabled by motion preference').disabled,true,'Waterfall respects global motion preference');
await click(named('Explore the floor'),'Explore remains available without motion');
assert.equal(transition().dataset.motion,'off','Global motion preference reaches the story');
assert.equal(cards().length,10,'All ten candidates are available without animation');
w.document.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));await settle();
assert.equal(transition(),null,'Escape dismisses transition');
assert.equal(w.document.activeElement.textContent.trim(),'Explore the floor','Focus returns to transition trigger');
await click(label('Walk through the decision'),'Guided presentation starts');
const tour=()=>w.document.querySelector('.guided-presentation');
assert.ok(tour(),'Tour dialog mounts');
assert.equal(tour().dataset.step,'0','Tour begins with manager question');
for(let i=1;i<=5;i++){
  await click(label('Next chapter'),`Next chapter ${i+1}`);
  assert.equal(tour().dataset.step,String(i),'Manual chapter advance matches step');
  if(i===1) assert.ok(tour().textContent.includes('541,425')&&tour().textContent.includes('3,764.90'),'Waterfall summary keeps gap and positive offset');
  if(i===3){
    const period=label('Presentation period');assert.ok(period,'Tour has a real period filter');
    period.value='last-month';period.dispatchEvent(new w.Event('change',{bubbles:true}));await settle();
    assert.ok(tour().querySelector('[data-testid="presentation-scope-totals"]').textContent.includes('39.73'),'June tour wagers reconcile');
    const bank=label('Presentation bank');bank.value='B-01';bank.dispatchEvent(new w.Event('change',{bubbles:true}));await settle();
    assert.ok(!tour().querySelector('[data-testid="presentation-scope-totals"]').textContent.includes('39.73'),'Tour bank drilldown changes aggregate');
    assert.equal(label('Analysis period preset').value,'full','Tour filters leave main scope intact');
  }
  if(i===4) assert.ok(tour().textContent.includes('68,699')&&tour().textContent.includes('218,258'),'Tour validation uses published holdout metrics');
  if(i===5) assert.ok(tour().textContent.includes('8,700')&&tour().textContent.includes('91,300'),'Tour plan shows correct spend and reserve');
}
await click(label('Previous chapter'),'Previous chapter available');
assert.equal(tour().dataset.step,'4','Manual back works');
w.document.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));await settle();
assert.equal(tour(),null,'Escape dismisses presentation');
assert.equal(w.document.activeElement.getAttribute('aria-label'),'Walk through the decision','Focus returns to Present');
assert.equal(w.document.querySelector('.workspace').hasAttribute('inert'),false,'Background becomes interactive again');
assert.notEqual(w.document.body.style.overflow,'hidden','Body scroll lock is released');
assert.equal(w.document.querySelector('.ace-overview h1').textContent,heroBefore,'Approved overview remains intact');
await click(label('Walk through the decision'),'Presentation can be reopened');
await click(label('Next chapter'),'Open evidence chapter again');
await click(named('Trace the finding',tour()),'Waterfall finding links to its source');
assert.equal(tour(),null,'Evidence navigation closes the presentation');
assert.equal(w.location.hash,'#evidence/q1-decomposition','Tour opens the precise evidence claim');
assert.ok(w.document.querySelector('#claim-q1-decomposition'),'Linked evidence is rendered');
assert.equal(errors.length,0,errors.join('\n'));
console.log('PASS: ten historical candidate identities/earnings/exposure, nine actual location histories, overlapping corrected inspection signal, manual story navigation/continue/reduced motion, modal isolation/focus/Escape, six presentation chapters and analytical totals.');
dom.window.close();
