/** DOM integration checks. These test state/logic, not pixel layout. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {JSDOM,VirtualConsole} from 'jsdom';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'public/data/dashboard.json'),'utf8'));
const compiled=await build({entryPoints:[path.join(root,'src/main.tsx')],bundle:true,write:false,format:'iife',platform:'browser',loader:{'.css':'empty'},define:{'process.env.NODE_ENV':'"production"'},logLevel:'silent'});
const errors=[];
const vc=new VirtualConsole();
vc.on('jsdomError',e=>errors.push(e.message));
const dom=new JSDOM('<!doctype html><html><body><script id="dashboard-payload" type="application/json"></script><div id="root"></div></body></html>',{url:'http://localhost/',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole:vc});
const {window:w}=dom;
w.document.getElementById('dashboard-payload').textContent=JSON.stringify(data);
w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
w.ResizeObserver=class {constructor(cb){this.cb=cb;}observe(el){this.cb([{target:el,contentRect:{width:900,height:310}}]);}unobserve(){}disconnect(){}};
w.URL.createObjectURL=()=> 'blob:test-export';w.URL.revokeObjectURL=()=>{};
w.addEventListener('error',e=>errors.push(e.error?.stack||e.message));
w.eval(compiled.outputFiles[0].text);
const settle=()=>new Promise(resolve=>setTimeout(resolve,100));
const text=()=>w.document.body.textContent;
const button=(label)=>[...w.document.querySelectorAll('button')].find(x=>x.textContent.trim()===label);
const click=async(label)=>{const el=button(label);assert.ok(el,`Button exists: ${label}`);el.click();await settle();};
const select=async(label,value)=>{const el=w.document.querySelector(`select[aria-label="${label}"]`);assert.ok(el,`Select exists: ${label}`);el.value=value;el.dispatchEvent(new w.Event('change',{bubbles:true}));await settle();};
await settle();await settle();
assert.ok(text().includes('$248.91m'),'Full-period wagers reconcile in rendered overview');
await select('Analysis period preset','june');
assert.ok(text().includes('$39.73m'),'June filter changes displayed wagers');
await select('Zone filter','Z-B40');
assert.ok(!text().includes('$39.73m'),'Zone filter changes totals');
await click('Floor explorer');
assert.ok(w.document.querySelectorAll('tbody tr').length>0,'Machine explorer has records');
const firstRow=w.document.querySelector('tbody tr');firstRow.click();await settle();
assert.ok(w.document.querySelector('[role="dialog"]'),'Machine drilldown opens');
w.document.querySelector('[aria-label="Close machine details"]').click();await settle();
await click('Demand & downtime');
assert.ok(text().includes('Unavailable hours by month'),'Downtime view renders');
await click('Guests & comps');
assert.ok(text().includes('$163.80m'),'Guest totals reconcile');
const guestOptions=[...w.document.querySelectorAll('select[aria-label="Guest group"] option')];
assert.ok(guestOptions.length>4,'Guest group drilldown has options');
await select('Guest group',guestOptions.find(o=>o.value!=='all').value);
assert.ok(!text().includes('$163.80m'),'Guest group changes totals');
await click('Model lab');
assert.ok(text().includes('$68,699')&&text().includes('$218,258'),'Model and baseline errors match reports');
await click('Action studio');
assert.ok(text().includes('$91,300'),'Recommended reserve matches catalog');
await click('What-if lab');
const slider=w.document.querySelector('[aria-label="Displaced play percentage"]');
assert.ok(slider,'Sensitivity slider exists');
assert.ok(text().includes('1.44 occupancy points'),'50% displacement doubles signage break-even');
await click('Build a portfolio');
assert.ok(text().includes('$8,700 committed'),'Catalog initial budget exact');
assert.equal(button('Export plan').disabled,false,'Valid portfolio exports');
w.document.querySelector('[aria-label="Remove Inspect a machine and verify its payout"]')?.click();
await click('Evidence');
assert.ok(w.document.querySelectorAll('.evidence-card').length>=20,'All claim evidence rendered');
const hrefs=[...w.document.querySelectorAll('.evidence-downloads a')].map(a=>a.getAttribute('href'));
for(const href of hrefs.filter(h=>!/^https:/.test(h)))assert.ok(fs.existsSync(path.join(root,'public',href)),`Download exists: ${href}`);
await click('Action studio');
await click('The recommendation');
const link=[...w.document.querySelectorAll('button')].find(b=>b.textContent.includes('Follow the evidence'));
link.click();await settle();
assert.ok(w.document.querySelector('#claim-q1-inspection'),'Action links to traceable evidence');
assert.equal(errors.length,0,errors.join('\n'));
console.log('PASS: seven routes, date/zone filters, machine dialog, guest group, model metrics, budget, sensitivity, downloads, evidence deep-link; no runtime errors.');
dom.window.close();
