/** DOM integration checks. These test state/logic, not pixel layout. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {JSDOM,VirtualConsole} from 'jsdom';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'public/data/dashboard.json'),'utf8'));
const compiled=await build({entryPoints:[path.join(root,'src/main.tsx')],bundle:true,write:false,format:'iife',platform:'browser',loader:{'.css':'empty'},define:{'process.env.NODE_ENV':'"production"'},logLevel:'silent'});
const errors=[];
const vc=new VirtualConsole();
vc.on('jsdomError',e=>errors.push(e.message));
const dom=new JSDOM('<!doctype html><html><body><script id="dashboard-payload" type="application/json"></script><div id="root"></div></body></html>',{url:'http://localhost/',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole:vc});
const {window:w}=dom;
w.document.getElementById('dashboard-payload').textContent=JSON.stringify(data);
w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
w.HTMLMediaElement.prototype.pause=()=>{};
w.HTMLMediaElement.prototype.play=()=>Promise.resolve();
const motionListeners=new Set();
const mediaQuery={matches:false,addEventListener:(_event,cb)=>motionListeners.add(cb),removeEventListener:(_event,cb)=>motionListeners.delete(cb)};
w.matchMedia=()=>mediaQuery;
w.ResizeObserver=class {constructor(cb){this.cb=cb;}observe(el){this.cb([{target:el,contentRect:{width:900,height:310}}]);}unobserve(){}disconnect(){}};
w.URL.createObjectURL=()=> 'blob:test-export';w.URL.revokeObjectURL=()=>{};
w.addEventListener('error',e=>errors.push(e.error?.stack||e.message));
w.eval(compiled.outputFiles[0].text);
const settle=()=>new Promise(resolve=>setTimeout(resolve,100));
const text=()=>w.document.body.textContent;
const button=(label)=>[...w.document.querySelectorAll('button')].find(x=>x.textContent.trim()===label);
const click=async(label)=>{const el=button(label);assert.ok(el,`Button exists: ${label}`);el.click();await settle();};
const select=async(label,value)=>{const el=w.document.querySelector(`select[aria-label="${label}"]`);assert.ok(el,`Select exists: ${label}`);el.value=value;el.dispatchEvent(new w.Event('change',{bubbles:true}));await settle();};
const readyDeadline=Date.now()+5000;
while(!w.document.querySelector('.metric-value')&&Date.now()<readyDeadline) await settle();
const introductionButton=(label)=>w.document.querySelector(`[aria-label="${label}"]`);
assert.equal(w.document.querySelector('.cinema-opening'),null,'Particle overview opens first');
assert.ok(w.document.querySelector('.particle-ace'),'Particle ace backdrop is present');
assert.equal(w.document.querySelectorAll('.ace-stat-card').length,4,'Four floating metric cards are present');
assert.ok(w.document.querySelector('.ace-stat-card').textContent.includes('$248.91m'),'Floating wagers reconcile with full-period data');
introductionButton('Show cinematic introduction').click();await settle();
assert.ok(w.document.querySelector('.cinema-opening'),'Topbar reopens introduction');
introductionButton('Skip cinematic introduction').click();await settle();
assert.equal(w.document.activeElement.id,'main-content','Skip transfers keyboard focus to dashboard');
assert.ok(text().includes('$248.91m'),'Full-period wagers reconcile in rendered overview');
const motionButton=()=>w.document.querySelector('[aria-label="Toggle animations"]');
assert.equal(w.document.querySelector('.app-shell').dataset.motion,'on','Motion starts enabled when allowed');
motionButton().click();await settle();
assert.equal(w.document.querySelector('.app-shell').dataset.motion,'off','Motion toggle stops animation');
assert.equal(w.document.querySelector('.ace-overview').dataset.active,'false','Floating cards stop with motion disabled');
assert.equal(w.localStorage.getItem('gilded-ace-motion'),'off','Motion preference persists');
motionButton().click();await settle();
assert.equal(w.localStorage.getItem('gilded-ace-motion'),'on','Motion can be restored');
mediaQuery.matches=true;motionListeners.forEach(cb=>cb());await settle();
assert.equal(w.document.querySelector('.app-shell').dataset.motion,'off','System reduced motion overrides stored preference');
assert.equal(motionButton().disabled,true,'Reduced-motion system setting is respected');
mediaQuery.matches=false;motionListeners.forEach(cb=>cb());await settle();
assert.equal(w.document.querySelector('.app-shell').dataset.motion,'on','System preference changes update the page');
const byLabel=(label)=>w.document.querySelector(`[aria-label="${label}"]`);
assert.equal(byLabel('Replay January 2025').getAttribute('aria-pressed'),'true','Replay starts in January without autoplay');
assert.ok(byLabel('Play floor replay'),'Playback starts paused');
byLabel('Replay June 2025').click();await settle();
assert.ok(w.document.querySelector('.month-total').textContent.includes('$39.73m'),'June replay agrees with property total');
assert.ok(w.document.querySelector('.month-trend-chart').getAttribute('aria-label').includes('June 2025 daily wagers'),'Monthly plot exposes its period and measure');
byLabel('Play floor replay').click();await settle();
assert.equal(byLabel('Replay January 2025').getAttribute('aria-pressed'),'true','Replay restarts at January from final month');
assert.ok(byLabel('Pause floor replay'),'Play begins playback');
byLabel('Replay March 2025').click();await settle();
assert.ok(byLabel('Play floor replay'),'Selecting a month pauses playback');
assert.ok(w.document.querySelector('.replay-meta').textContent.includes('closed March 3'),'Closure annotation uses historical date');
byLabel('Play floor replay').click();await settle();
await new Promise(resolve=>setTimeout(resolve,2900));
assert.equal(byLabel('Replay April 2025').getAttribute('aria-pressed'),'true','Playback advances through actual months');
byLabel('Monthly expected win').click();await settle();
assert.ok(byLabel('Play floor replay'),'Changing the chart measure pauses playback');
assert.equal(byLabel('Monthly expected win').getAttribute('aria-pressed'),'true','Monthly measure changes');
assert.ok(w.document.querySelector('.month-trend-chart').getAttribute('aria-label').includes('daily expected win'),'Plot accessibility description follows measure');
byLabel('Monthly wagers').click();await settle();
motionButton().click();await settle();
assert.equal(byLabel('Play floor replay').disabled,true,'Playback cannot run with motion off');
byLabel('Replay May 2025').click();await settle();
assert.equal(byLabel('Replay May 2025').getAttribute('aria-pressed'),'true','Manual historical inspection works without motion');
motionButton().click();await settle();
await select('Analysis period preset','june');
assert.ok(w.document.querySelector('.ace-stat-card').textContent.includes('$39.73m'),'June filter changes floating wagers');
await select('Zone filter','Z-B40');
assert.ok(!text().includes('$39.73m'),'Zone filter changes totals');
assert.equal(w.document.querySelectorAll('.zone-ranking-row').length,1,'Location comparison follows selected zone');
byLabel('Explore Back Forty').click();await settle();
assert.equal(w.document.querySelector('select[aria-label="Zone filter"]').value,'Z-B40','Zone visualization opens matching floor drilldown');
await click('Floor explorer');
assert.ok(w.document.querySelectorAll('tbody tr').length>0,'Machine explorer has records');
const firstRow=w.document.querySelector('tbody tr');firstRow.click();await settle();
assert.ok(w.document.querySelector('[role="dialog"]'),'Machine drilldown opens');
w.document.querySelector('[aria-label="Close machine details"]').click();await settle();
await click('Demand & downtime');
assert.ok(text().includes('Unavailable hours by month'),'Downtime view renders');
await click('Guests & comps');
assert.ok(text().includes('$163.80m'),'Guest totals reconcile');
assert.ok(w.document.querySelector('.recharts-yAxis')?.textContent.includes('$0'),'Negative guest bars include a zero baseline');
const guestOptions=[...w.document.querySelectorAll('select[aria-label="Guest group"] option')];
assert.ok(guestOptions.length>4,'Guest group drilldown has options');
await select('Guest group',guestOptions.find(o=>o.value!=='all').value);
assert.ok(!text().includes('$163.80m'),'Guest group changes totals');
await click('Model lab');
assert.ok(text().includes('$68,699')&&text().includes('$218,258'),'Model and baseline errors match reports');
await click('Action studio');
assert.ok(text().includes('$91,300'),'Recommended reserve matches catalog');
await click('What-if lab');
const slider=w.document.querySelector('[aria-label="Displaced play percentage"]');
assert.ok(slider,'Sensitivity slider exists');
assert.ok(text().includes('1.44 occupancy points'),'50% displacement doubles signage break-even');
await click('Build a portfolio');
assert.ok(text().includes('$8,700 committed'),'Catalog initial budget exact');
assert.equal(button('Export plan').disabled,false,'Valid portfolio exports');
w.document.querySelector('[aria-label="Remove Inspect a machine and verify its payout"]')?.click();
await click('Evidence');
assert.ok(w.document.querySelectorAll('.evidence-card').length>=20,'All claim evidence rendered');
const hrefs=[...w.document.querySelectorAll('.evidence-downloads a')].map(a=>a.getAttribute('href'));
for(const href of hrefs.filter(h=>!/^https:/.test(h)))assert.ok(fs.existsSync(path.join(root,'public',href)),`Download exists: ${href}`);
await click('Action studio');
await click('The recommendation');
const link=[...w.document.querySelectorAll('button')].find(b=>b.textContent.includes('Follow the evidence'));
link.click();await settle();
assert.ok(w.document.querySelector('#claim-q1-inspection'),'Action links to traceable evidence');
assert.equal(errors.length,0,errors.join('\n'));
console.log('PASS: seven routes, motion preference and system changes, monthly performance playback/measure selection, zone visualization drilldown, date/zone filters, machine dialog, guest group, model metrics, budget, sensitivity, downloads, evidence deep-link; no runtime errors.');
dom.window.close();
