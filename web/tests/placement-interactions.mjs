/** Placement route integration with actual exported predictions and offline data. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {JSDOM,VirtualConsole} from 'jsdom';
import {placementScenario} from '../src/placement.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>JSON.parse(fs.readFileSync(path.join(root,'public/data',name),'utf8'));
const data=read('dashboard.json'),report=read('placement_model.json');
const compiled=await build({entryPoints:[path.join(root,'src/main.tsx')],bundle:true,write:false,format:'iife',platform:'browser',loader:{'.css':'empty'},define:{'process.env.NODE_ENV':'"production"'},logLevel:'silent'});
const errors=[],vc=new VirtualConsole();vc.on('jsdomError',e=>errors.push(e.message));
const dom=new JSDOM('<!doctype html><div id="root"></div><script id="dashboard-payload" type="application/json"></script><script id="placement-payload" type="application/json"></script>',{url:'http://localhost/#placement',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole:vc});
const w=dom.window;
w.document.getElementById('dashboard-payload').textContent=JSON.stringify(data);
w.document.getElementById('placement-payload').textContent=JSON.stringify(report);
w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
w.matchMedia=()=>({matches:true,addEventListener(){},removeEventListener(){}});
w.ResizeObserver=class{observe(){}unobserve(){}disconnect(){}};
w.fetch=()=>{throw Error('Offline route must not fetch data');};
w.addEventListener('error',e=>errors.push(e.error?.stack||e.message));
w.eval(compiled.outputFiles[0].text);
const settle=()=>new Promise(r=>setTimeout(r,70)),body=()=>w.document.body.textContent;
for(let i=0;i<60&&!w.document.querySelector('#placement-machine');i++)await settle();
assert.ok(w.document.querySelector('#placement-machine'),'Placement deep link loads from embedded data');
assert.equal(w.document.querySelector('.cinema-opening'),null,'Deep link bypasses introduction');
const change=async(id,value)=>{const el=w.document.getElementById(id);assert.ok(el,id);el.value=value;el.dispatchEvent(new w.Event('change',{bubbles:true}));await settle();};
const click=async(label)=>{const el=[...w.document.querySelectorAll('button')].find(x=>x.textContent.trim()===label);assert.ok(el,label);el.click();await settle();};
const selectDestination=async(machine,location)=>{
 await change('placement-machine',machine.id);
 const zone=report.zones.find(z=>z.id===location.zone);
 [...w.document.querySelectorAll('.placement-zone')].find(b=>b.textContent.startsWith(zone.name)).click();await settle();
 await change('placement-destination',location.id);
};
assert.ok(body().includes('Keeping the current floor is a valid choice.'));
assert.ok(body().includes('$91,300'),'Retained recommended plan is included');
let vacant,swap,unsupported;
for(const m of report.machines)for(const l of report.locations){
 const s=placementScenario(report,m.id,l.id,.5,8700,2);
 if(s.valid&&s.kind==='move'&&!vacant)vacant={m,l,s};
 if(s.valid&&s.kind==='swap'&&!swap)swap={m,l,s};
 if(!s.valid&&!m.predictions[l.zone]?.supported&&!unsupported)unsupported={m,l};
}
assert.ok(vacant&&swap&&unsupported);
await selectDestination(vacant.m,vacant.l);
assert.ok(body().includes('One move. A measurable hypothesis.'));
assert.ok(body().includes('$1,800')&&body().includes('$89,500'),'One move prices lead/downtime and retained budget');
await selectDestination(swap.m,swap.l);
assert.equal(w.document.querySelectorAll('.placement-move-list>div').length,2,'Swap displays both moved machines');
assert.ok(body().includes('$3,600')&&body().includes('$87,700'),'Both moves are paid');
const checkbox=w.document.querySelector('.placement-checkbox input');checkbox.click();await settle();
assert.ok(body().includes('$96,400'),'Removing retained plan frees exactly $8,700');
const slider=w.document.querySelector('[aria-label="Placement displacement percentage"]');
Object.getOwnPropertyDescriptor(w.HTMLInputElement.prototype,'value').set.call(slider,'100');
slider.dispatchEvent(new w.Event('input',{bubbles:true}));slider.dispatchEvent(new w.Event('change',{bubbles:true}));await settle();
assert.ok(w.document.querySelector('.slider-label').textContent.includes('100%'));
await selectDestination(unsupported.m,unsupported.l);
assert.ok(body().includes('More evidence is needed.')&&body().includes('Insufficient evidence'));
assert.equal(w.document.querySelector('.placement-result-grid'),null,'Unsupported placement shows no net dollar result');
await click('Model & validation');
assert.ok(body().includes('$3.69')&&body().includes('$4.29')&&body().includes('88.5%'));
assert.ok(body().includes('49 rows')&&body().includes('77 rows'),'Origin exclusions disclosed');
assert.ok(body().includes(report.limitations[0]),'Exported limitations are visible');
await click('Model lab');
assert.ok(body().includes('8.8%')&&body().includes('higher'),'Losing forecast challenger disclosed');
await click('Evidence');assert.ok(w.document.getElementById('claim-placement-model'),'Placement evidence is traceable');
assert.deepEqual(errors,[]);
dom.window.close();
console.log('PASS: offline Placement Lab deep link, vacant move, two-sided swap, retained budget, displacement, unsupported abstention, validation metrics, limitations and evidence.');
